"""Regenerate docs/PROTOCOL.md from the schema, the metric catalogue and a real run.

    python tools/build_protocol_doc.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from netcoop import catalog, knowledge  # noqa: E402
from netcoop.orchestrator import diagnose  # noqa: E402
from netcoop.protocol import SCHEMA_PATH  # noqa: E402


def example(messages, type_, sender=None):
    for m in messages:
        if m["type"] == type_ and (sender is None or m["sender"] == sender):
            m = json.loads(json.dumps(m))
            p = m["payload"]
            if type_ == "FINDING":
                p["observations"] = p["observations"][:2]
                for h in p["hypotheses"]:
                    h["evidence"] = h["evidence"][:1]
                p["hypotheses"] = p["hypotheses"][:1]
            return json.dumps(m, indent=2)
    return "{}"


def main():
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    run = diagnose((ROOT / "data/scenarios/conflicting_wifi_vs_congestion.json").read_text(encoding="utf-8"))
    msgs = run["messages"]
    th = knowledge.thresholds()
    out = ["# netcoop-msg/1.0 protocol reference", "",
           "_Generated by `python tools/build_protocol_doc.py` from `schemas/message.schema.json`, "
           "`netcoop/catalog.py`, `config/thresholds.json` and a real run of the "
           "`conflicting_wifi_vs_congestion` scenario._", "",
           "## 1. Envelope", "",
           "Every inter-agent message is a JSON object with exactly these fields. The message bus validates it "
           "against the JSON Schema before delivery; invalid messages are not delivered and produce an `ERROR` "
           "message naming the faulty field.", "",
           "| Field | Type | Required | Meaning |", "|---|---|---|---|"]
    req = set(schema["required"])
    for name, spec in schema["properties"].items():
        t = spec.get("type") or ("enum" if "enum" in spec else "const")
        if isinstance(t, list):
            t = " / ".join(t)
        desc = spec.get("description", "")
        if "enum" in spec:
            desc = (desc + " One of: " + ", ".join(f"`{e}`" for e in spec["enum"])).strip()
        if "const" in spec:
            desc = f"Always `{spec['const']}`. " + desc
        out.append(f"| `{name}` | {t} | {'yes' if name in req else 'no'} | {desc} |")

    out += ["", "## 2. Message types", "",
            "| Type | Sender → recipient | Purpose | Payload |", "|---|---|---|---|",
            "| `TASK` | orchestrator → agent | start a step | `action`: normalize / analyze / correlate / report; optional `notes` |",
            "| `TELEMETRY` | ingestion_agent → `*` | canonical telemetry for everyone | canonical dataset (section 5) |",
            "| `FINDING` | specialist / external → correlation_agent; correlation_agent → reporting_agent | evidence and hypotheses | section 3 |",
            "| `QUERY` | correlation_agent → specialist | targeted follow-up question | `question`, `args`, `reason` |",
            "| `RESPONSE` | specialist → correlation_agent | answer to a QUERY (`in_reply_to` required) | `question`, `supports`, `refutes`, `evidence`, `detail` |",
            "| `ERROR` | any agent or the bus | failure that did not stop the run | `code`, `message`, `details` |",
            "| `REPORT` | reporting_agent → orchestrator | final result | `report` (JSON), `markdown` |",
            "", "## 3. FINDING payload", ""]
    defs = schema["$defs"]
    for block in ("finding", "hypothesis", "evidence"):
        d = defs[block]
        out += [f"**{block}**", "", "| Field | Type | Required | Meaning |", "|---|---|---|---|"]
        for name, spec in d["properties"].items():
            t = spec.get("type") or ("enum" if "enum" in spec else "ref" if "$ref" in spec else "")
            if "items" in spec:
                item = spec["items"].get("type") or spec["items"].get("$ref", "").split("/")[-1]
                t = f"array of {item}"
            if isinstance(t, list):
                t = " / ".join(t)
            desc = spec.get("description", "")
            if "enum" in spec:
                desc = (desc + " One of: " + ", ".join(f"`{e}`" for e in spec["enum"])).strip()
            if "minimum" in spec:
                desc = (desc + f" Range {spec['minimum']}–{spec['maximum']}.").strip()
            out.append(f"| `{name}` | {t} | {'yes' if name in d.get('required', []) else 'no'} | {desc} |")
        out.append("")

    out += ["## 4. QUERY questions", "",
            "| `question` | Answered by | `args` | Answer semantics |", "|---|---|---|---|",
            "| `correlate_metrics` | performance_agent | `device`, `x` (default `link_utilization_pct`), `y` (default `latency_ms`) | Pearson r between `y` on the device and `x` on the device or any device upstream (best match, ≥ 4 paired samples). r ≥ 0.6 supports `link_congestion` and refutes `path_latency`; r ≤ 0.3 the reverse; otherwise inconclusive. |",
            "| `baseline_connectivity` | performance_agent | `cause` | Healthy loss/latency on all devices supports the service fault in `cause`; problems on ≥ 50 % of devices refute it. |",
            "| `device_detail` | infrastructure_agent | `device` | Critical status + errors supports `hardware_failure` over `device_overload`; saturated CPU/memory with clean interfaces the reverse. |",
            "| `error_trend` | infrastructure_agent | `device` | CRC / interface errors rising across ≥ 3 samples while the link is not saturated supports `interface_fault` and refutes `link_congestion`. |",
            "| `scope_check` | connectivity_agent | `device`, `cause` | Healthy wired neighbours support `weak_wifi_signal`; degraded neighbours refute it. With `cause=upstream_device_outage`: at least half the devices below the silent device cut off supports the outage. |",
            "", "`supports` and `refutes` are fault ids (or `null`). The correlation agent applies +0.10 to a supported fault and −0.15 to a refuted one.", "",
            "## 5. Canonical metrics, units and thresholds", "",
            "All values in FINDING evidence and in TELEMETRY are in these units. Thresholds come from `config/thresholds.json` (direction `low` means smaller is worse).", "",
            "| Metric | Unit | Valid range | Warning | Critical | Owner | Meaning |", "|---|---|---|---|---|---|---|"]
    for m, (unit, lo, hi, own, desc) in catalog.METRICS.items():
        t = th.get(m, {})
        hi_s = "∞" if hi == float("inf") else f"{hi:g}"
        w = f"{'≤' if t.get('direction') == 'low' else '≥'} {t['warning']}" if t else "–"
        c = f"{'≤' if t.get('direction') == 'low' else '≥'} {t['critical']}" if t else "–"
        out.append(f"| `{m}` | {unit} | {lo:g} – {hi_s} | {w} | {c} | {own} | {desc} |")
    out += ["",
            "Pseudo-metrics used in evidence:", "",
            "| Metric | Unit | Produced by | Meaning |", "|---|---|---|---|",
            "| `device_status` | state | infrastructure_agent | `healthy`, `degraded` (warning) or `down` (critical), normalised from any status word (OK, Warning, Critical, up, red, …) |",
            "| `telemetry_missing` | bool | connectivity_agent | device is in the topology but sent nothing |",
            "| `downstream_impact` | count | connectivity_agent | devices below a silent device that are down, heavily lossy or silent |",
            "| `corr(x,y)` | ratio | performance_agent | Pearson correlation returned in a RESPONSE |", "",
            "Severity grades: `normal` (strength 0), `warning` (0.6 at the threshold, rising to 0.9), `critical` (0.9, rising to 1.0).", "",
            "## 6. Telemetry input formats", "",
            "The ingestion agent accepts any of these (mixed freely) and reports every translation:", "",
            "```json", json.dumps({"timestamp": "2026-10-31T10:05:00Z", "device_id": "SW_CAMPUS_4",
                                   "metrics": {"cpu_utilization_pct": 99.9, "latency_ms": 926.5}, "status": "Critical"}, indent=2),
            "```", "", "Batch with topology (`schema_version` 0.x or 1.x; newer versions parsed best effort):", "", "```json",
            json.dumps({"schema_version": "1.1", "incident_id": "INC-001",
                        "topology": {"devices": [{"id": "CORE_01", "type": "core", "upstream": None},
                                                 {"id": "AP_01", "type": "ap", "segment": "hostel_A", "upstream": "CORE_01", "medium": "wireless"}]},
                        "records": [{"device_id": "AP_01", "timestamp": "2026-10-31T10:05:00Z", "metrics": {"rssi_dbm": -79}}],
                        "services": {"dns": {"failure_rate": 0.4, "response_ms": 1800}},
                        "external_findings": ["<netcoop-msg/1.0 or 0.9 FINDING>"]}, indent=2),
            "```", "",
            "Also: flat records (`{\"host\": \"AP-3\", \"ts\": 1730000000, \"rtt\": \"0.25 s\"}`), NDJSON, CSV, "
            "`topology.nodes/edges` with undirected links (oriented by device tier), per-record or batch `units` "
            "maps, value-with-unit objects (`{\"value\": 12, \"unit\": \"ms\"}`), epoch seconds or milliseconds.", "",
            "## 7. Legacy netcoop-msg/0.9 and the adapter", "", "```json",
            json.dumps({"version": "0.9", "from": "campus_nms_probe", "to": "correlation_agent", "kind": "finding",
                        "sent_at": 1793440200, "data": {"issue": "Uplink congestion on hostel distribution", "conf": 0.7,
                                                        "devices": ["HOSTEL_DIST_SW_01"],
                                                        "readings": {"ifUtil": "96%", "outDiscards": 280}}}, indent=2),
            "```", "",
            "The adapter maps `from/to/kind/sent_at/data` to the 1.0 envelope, converts `readings` with the same "
            "field and unit translator as telemetry, maps the free-text `issue` to a fault id by keywords, and wraps "
            "everything in a FINDING with `agent_role: external`. The upgraded message is then validated like any "
            "other and carries `context.protocol_note`.", "",
            "## 8. Real messages from a run", "",
            "FINDING (performance_agent, trimmed to two observations):", "", "```json", example(msgs, "FINDING", "performance_agent"), "```", "",
            "QUERY:", "", "```json", example(msgs, "QUERY"), "```", "",
            "RESPONSE:", "", "```json", example(msgs, "RESPONSE"), "```", "",
            "ERROR produced by the bus for an invalid external message (from `interop_legacy_mixed.json`):", "", "```json"]
    run2 = diagnose((ROOT / "data/scenarios/interop_legacy_mixed.json").read_text(encoding="utf-8"))
    out += [example(run2["messages"], "ERROR"), "```", ""]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "PROTOCOL.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/PROTOCOL.md")


if __name__ == "__main__":
    main()
